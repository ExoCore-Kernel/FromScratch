function shutdown() {
  for (const session of sessions.values()) stopSession(session, 'server shutdown');
  httpServer.close(() => process.exit(0));
  setTimeout(() => process.exit(0), 1500).unref();
}
process.on('SIGINT', shutdown);
process.on('SIGTERM', shutdown);
