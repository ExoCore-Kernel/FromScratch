app.get('/api/learning/source', async (request, response) => {
  const symbol = String(request.query?.symbol ?? '');
  if (!/^[A-Za-z_][A-Za-z0-9_]{0,127}$/.test(symbol)) {
    return response.status(400).json({ok: false, output: 'Invalid C symbol name.'});
  }

  try {
    const result = await findLearningSource(symbol);
    if (!result) {
      return response.status(404).json({
        ok: false,
        output: 'This block is generated inline or its runtime function could not be found.',
      });
    }
    response.json({ok: true, symbol, ...result});
  } catch (error) {
    response.status(500).json({ok: false, output: error instanceof Error ? error.message : String(error)});
  }
});

app.get('/api/assets', async (_request, response) => response.json({ok: true, assets: await listAssets()}));

app.post('/api/assets/upload', async (request, response) => {
  const files = Array.isArray(request.body?.files) ? request.body.files : [];
  if (files.length > 32) return response.status(413).json({ok: false, output: 'Upload at most 32 files at once.'});
  const saved = [];
  for (const item of files) {
    const name = safeFileName(item?.name);
    const data = Buffer.from(String(item?.dataBase64 ?? ''), 'base64');
    if (data.length > 32 * 1024 * 1024) return response.status(413).json({ok: false, output: `${name} is larger than 32 MiB.`});
    await writeFile(path.join(assetsDirectory, name), data);
    saved.push(name);
  }
  response.json({ok: true, saved, assets: await listAssets()});
});

app.post('/api/assets/import-server', async (_request, response) => {
  const entries = await readdir(serverImportsDirectory, {withFileTypes: true});
  const imported = [];
  for (const entry of entries) {
    if (!entry.isFile()) continue;
    const name = safeFileName(entry.name);
    await copyFile(path.join(serverImportsDirectory, entry.name), path.join(assetsDirectory, name));
    imported.push(name);
  }
  response.json({ok: true, imported, assets: await listAssets(), folder: serverImportsDirectory});
});

app.delete('/api/assets/:name', async (request, response) => {
  const name = safeFileName(request.params.name);
  await unlink(path.join(assetsDirectory, name)).catch(() => {});
  response.json({ok: true, assets: await listAssets()});
});

app.post('/api/build-run', async (request, response) => {
  if (!(await commandExists('qemu-system-x86_64')) || !(await commandExists('websockify'))) {
    response.status(503).json({ok: false, stage: 'tools', output: 'Missing qemu-system-x86_64 or websockify.'});
    return;
  }
  for (const existing of sessions.values()) if (existing.running) stopSession(existing, 'replaced by a new run');
  const build = await buildKernel(request.body?.code);
  if (!build.ok) {
    if (build.work) await rm(build.work, {recursive: true, force: true});
    response.status(build.stage === 'validation' ? 400 : 422).json(build);
    return;
  }
  try {
    const session = await startQemuSession(build);
    response.json({
      ok: true, stage: 'run', sessionId: session.id, running: true,
      kernelBytes: session.kernelBytes, isoBytes: session.isoBytes, assetCount: session.assetCount, websockifyPort: session.websockifyPort,
      buildOutput: session.buildOutput,
      output: `Built a bootable x86_64 ISO (${session.isoBytes} bytes) and started QEMU with a 1024×768 display.`,
    });
  } catch (error) {
    await rm(build.work, {recursive: true, force: true});
    response.status(500).json({ok: false, stage: 'qemu', output: error instanceof Error ? error.message : String(error)});
  }
});

app.post('/api/export-iso', async (request, response) => {
  const build = await buildKernel(request.body?.code);
  if (!build.ok) {
    if (build.work) await rm(build.work, {recursive: true, force: true});
    response.status(build.stage === 'validation' ? 400 : 422).json(build);
    return;
  }
  const isoPath = path.join(build.work, 'blockos-x86_64.iso');
  response.download(isoPath, 'blockos-x86_64.iso', async () => {
    await rm(build.work, {recursive: true, force: true});
  });
});

app.get('/api/run-session/:id', (request, response) => {
  const session = sessions.get(request.params.id);
  if (!session) return response.status(404).json({ok: false, output: 'That QEMU session no longer exists.'});
  response.json(publicSession(session));
});

app.post('/api/run-session/:id/input', (request, response) => {
  const session = sessions.get(request.params.id);
  if (!session) return response.status(404).json({ok: false, output: 'That QEMU session no longer exists.'});
  if (!session.running || !session.child.stdin.writable) return response.status(409).json({ok: false, output: 'QEMU is no longer running.'});
  const input = String(request.body?.input ?? '');
  if (Buffer.byteLength(input, 'utf8') > MAX_INPUT_BYTES) return response.status(413).json({ok: false, output: 'Input is too large.'});
  session.child.stdin.write(input);
  response.json({ok: true, bytes: Buffer.byteLength(input, 'utf8')});
});

app.post('/api/run-session/:id/stop', (request, response) => {
  const session = sessions.get(request.params.id);
  if (!session) return response.status(404).json({ok: false, output: 'That QEMU session no longer exists.'});
  stopSession(session, 'stopped by user');
  response.json({ok: true});
});

